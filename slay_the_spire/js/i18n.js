class I18nManager {
  constructor() {
    this.supportedLanguages = ['id', 'en', 'zh', 'ja'];
    this.currentLanguage = this.detectLanguage();
  }

  detectLanguage() {
    try {
      const saved = localStorage.getItem('spire_language');
      if (saved && this.supportedLanguages.includes(saved)) {
        return saved;
      }
    } catch (e) {
      // ignore
    }
    return 'id'; // Default Bahasa Indonesia
  }

  getLanguage() {
    return this.currentLanguage;
  }

  setLanguage(langCode) {
    if (!this.supportedLanguages.includes(langCode)) return;
    this.currentLanguage = langCode;
    try {
      localStorage.setItem('spire_language', langCode);
    } catch (e) {
      // ignore
    }

    // Apply translations to all DOM elements
    this.applyTranslations();

    // Update active state on language buttons
    const btns = document.querySelectorAll('.lang-btn');
    btns.forEach(b => {
      if (b.dataset.lang === langCode) b.classList.add('active');
      else b.classList.remove('active');
    });

    // Re-render UI components in app if available
    if (window.spireApp) {
      if (typeof window.spireApp.renderTopHud === 'function') window.spireApp.renderTopHud();
      if (typeof window.spireApp.renderHeroSelectorTabs === 'function') window.spireApp.renderHeroSelectorTabs();
      if (typeof window.spireApp.renderHeroShowcase === 'function' && window.spireApp.selectedHeroKey) {
        window.spireApp.renderHeroShowcase(window.spireApp.selectedHeroKey);
      }
      if (typeof window.spireApp.renderMap === 'function' && window.gameState && window.gameState.map) {
        window.spireApp.renderMap();
      }
      if (typeof window.spireApp.renderCombatUI === 'function' && window.spireCombat && window.spireCombat.isActive) {
        window.spireApp.renderCombatUI();
      }
    }
  }

  t(key, fallback = '') {
    if (I18N_DICTIONARY[key]) {
      return I18N_DICTIONARY[key][this.currentLanguage] || I18N_DICTIONARY[key]['id'] || fallback;
    }
    return fallback || key;
  }

  applyTranslations() {
    // 1. Elements with data-i18n
    const elems = document.querySelectorAll('[data-i18n]');
    elems.forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = this.t(key);
      if (text) {
        el.textContent = text;
      }
    });

    // 2. Elements with data-i18n-title
    const titleElems = document.querySelectorAll('[data-i18n-title]');
    titleElems.forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      const text = this.t(key);
      if (text) {
        el.setAttribute('title', text);
      }
    });

    // 3. Elements with data-i18n-html
    const htmlElems = document.querySelectorAll('[data-i18n-html]');
    htmlElems.forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      const text = this.t(key);
      if (text) {
        el.innerHTML = text;
      }
    });
  }
}

// Global instance
